/** Stock-document event names (explicit action endpoints, outline 1.8). */
export type StockTransactionEvent =
  | 'update'
  | 'submit'
  | 'approve'
  | 'reject'
  | 'post'
  | 'cancel'
  | 'reverse';

/**
 * from-status → allowed events (docs/status-transitions.md §2).
 * `submit` lands on APPROVED directly when no approval workflow matches
 * (the resolution happens in the service; the transition here only says
 * submit is legal from DRAFT).
 */
const TRANSITIONS: Record<StockDocumentStatus, readonly StockTransactionEvent[]> =
  {
    [StockDocumentStatus.DRAFT]: ['update', 'submit', 'cancel'],
    [StockDocumentStatus.PENDING_APPROVAL]: ['approve', 'reject', 'cancel'],
    [StockDocumentStatus.APPROVED]: ['post', 'cancel'],
    [StockDocumentStatus.REJECTED]: [],
    [StockDocumentStatus.POSTED]: ['reverse'],
    [StockDocumentStatus.CANCELED]: [],
    [StockDocumentStatus.REVERSED]: [],
  };

export function canTransition(
  from: StockDocumentStatus,
  event: StockTransactionEvent,
): boolean {
  return TRANSITIONS[from].includes(event);
}

/** Human-readable transition failure message for the 409 envelope. */
export function transitionError(
  from: StockDocumentStatus,
  event: StockTransactionEvent,
): string {
  const allowed = TRANSITIONS[from];
  return `Cannot ${event} a ${from} stock transaction${
    allowed.length > 0 ? ` (allowed: ${allowed.join(', ')})` : ' (terminal status)'
  }.`;
}
