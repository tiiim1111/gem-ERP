import { PERMISSIONS } from '@gemerp/shared';
import { StockDocumentStatus, StockTransactionType } from '@prisma/client';

/**
 * Pure domain rules for stock transaction documents (spec §13,
 * docs/status-transitions.md §2). Kept free of Nest/Prisma clients so the
 * state machine is unit-testable without any infrastructure.
 */

/** How a posted transaction of a given type moves stock. */
export type MovementDirection = 'IN' | 'OUT' | 'MOVE';

/**
 * Direction per type. REVERSAL is intentionally absent: its ledger entries are
 * always the negation of the reversed transaction's entries, never derived
 * from a direction map.
 */
export const TYPE_DIRECTION: Record<
  Exclude<StockTransactionType, 'REVERSAL'>,
  MovementDirection
> = {
  [StockTransactionType.OPENING_BALANCE]: 'IN',
  [StockTransactionType.PURCHASE_RECEIPT]: 'IN',
  [StockTransactionType.NON_PURCHASE_RECEIPT]: 'IN',
  [StockTransactionType.RETURN_FROM_EMPLOYEE]: 'IN',
  [StockTransactionType.INTER_BRANCH_TRANSFER_IN]: 'IN',
  [StockTransactionType.ADJUSTMENT_INCREASE]: 'IN',
  [StockTransactionType.ISSUE_TO_EMPLOYEE]: 'OUT',
  [StockTransactionType.ISSUE_TO_DEPARTMENT]: 'OUT',
  [StockTransactionType.RETURN_TO_SUPPLIER]: 'OUT',
  [StockTransactionType.INTER_BRANCH_TRANSFER_OUT]: 'OUT',
  [StockTransactionType.ADJUSTMENT_DECREASE]: 'OUT',
  [StockTransactionType.MAINTENANCE_ISSUE]: 'OUT',
  [StockTransactionType.DISPOSAL]: 'OUT',
  [StockTransactionType.LOCATION_TRANSFER]: 'MOVE',
};

export function directionOf(
  type: StockTransactionType,
): MovementDirection | null {
  if (type === StockTransactionType.REVERSAL) {
    return null;
  }
  return TYPE_DIRECTION[type];
}

